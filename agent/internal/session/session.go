// Package session generates the compositor configuration for the display
// session (Weston kiosk-shell, ADR-0004) from the DRM connectors and the
// per-output display configuration received from Castmill.
package session

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/castmill/castmill-os/agent/internal/api"
	"github.com/castmill/castmill-os/agent/internal/config"
)

// AppID is the Wayland app ID of the player instance for an output; the
// compositor pins that window to the output.
func AppID(output string) string { return "castmill-output-" + output }

var (
	validName = regexp.MustCompile(`^[A-Za-z0-9_.-]+$`)
	validMode = regexp.MustCompile(`^(preferred|current|\d{2,5}x\d{2,5}(@\d{2,3}(\.\d+)?)?)$`)
)

var transforms = map[string]bool{
	"": true, "normal": true, "rotate-90": true, "rotate-180": true, "rotate-270": true,
	"flipped": true, "flipped-rotate-90": true, "flipped-rotate-180": true, "flipped-rotate-270": true,
}

// Connectors lists DRM connector names (all, connected or not), so outputs
// plugged in later already have their configuration.
func Connectors(sysRoot string) []string {
	paths, _ := filepath.Glob(filepath.Join(sysRoot, "sys/class/drm/card*-*"))
	seen := map[string]bool{}
	var out []string
	for _, p := range paths {
		if _, err := os.Stat(filepath.Join(p, "status")); err != nil {
			continue
		}
		base := filepath.Base(p)
		name := base[strings.Index(base, "-")+1:]
		if validName.MatchString(name) && !seen[name] {
			seen[name] = true
			out = append(out, name)
		}
	}
	sort.Strings(out)
	return out
}

// LoadDisplay reads display.json (missing file: empty configuration).
func LoadDisplay(path string) map[string]api.OutputConfig {
	m := map[string]api.OutputConfig{}
	_ = config.ReadJSON(path, &m)
	return m
}

// WestonINI renders weston.ini. Invalid values from the backend are replaced
// by safe defaults rather than breaking the session.
func WestonINI(connectors []string, display map[string]api.OutputConfig) string {
	var b strings.Builder
	b.WriteString("# Generated by castmill-agent session-config. Do not edit.\n")
	b.WriteString("[core]\nshell=kiosk\nidle-time=0\nrequire-input=false\nmodules=systemd-notify.so\n\n")
	b.WriteString("[shell]\nallow-zap=false\n\n")
	for _, name := range connectors {
		oc := display[name]
		mode := oc.Mode
		if mode == "" || !validMode.MatchString(mode) {
			mode = "preferred"
		}
		if oc.Disabled {
			mode = "off"
		}
		tr := oc.Transform
		if !transforms[tr] || tr == "" {
			tr = "normal"
		}
		fmt.Fprintf(&b, "[output]\nname=%s\nmode=%s\ntransform=%s\n", name, mode, tr)
		if oc.Scale >= 1 && oc.Scale <= 4 && oc.Scale == float64(int(oc.Scale)) {
			fmt.Fprintf(&b, "scale=%d\n", int(oc.Scale))
		}
		fmt.Fprintf(&b, "app-ids=%s\n\n", AppID(name))
	}
	return b.String()
}

// Disabled lists outputs switched off in the display configuration.
func Disabled(display map[string]api.OutputConfig) []string {
	var out []string
	for n, oc := range display {
		if oc.Disabled && validName.MatchString(n) {
			out = append(out, n)
		}
	}
	sort.Strings(out)
	return out
}
