#!/usr/bin/env python3
"""Pin the Yocto layers of every build target to exact commits.

Usage: uvx --with pyyaml python scripts/lock-layers.py [--check]

For each target (kas/x86-64.yml, kas/rpi5.yml, kas/vm-arm64.yml) it reads the
repositories of the target and its includes, resolves each repository's
branch to its current head commit with `git ls-remote` (no clone), and writes
kas/<target>.lock.yml. kas uses the lock file automatically when it builds
that target, so every build of the same castmill-os commit uses the same
layers.

Run it to move to newer layer commits (then review the diff, build and
commit). --check only reports whether the lock files are up to date.
"""
import os
import subprocess
import sys

import yaml

KAS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "kas")
TARGETS = ["x86-64.yml", "rpi5.yml", "vm-arm64.yml"]


def load(name, seen=None):
    """Repositories of a kas file and its includes (later files win)."""
    seen = seen or set()
    if name in seen:
        return {}
    seen.add(name)
    with open(os.path.join(KAS_DIR, name)) as f:
        doc = yaml.safe_load(f) or {}
    repos = {}
    for inc in (doc.get("header") or {}).get("includes") or []:
        inc = inc if isinstance(inc, str) else inc.get("file")
        repos.update(load(os.path.basename(inc), seen))
    for repo_name, repo in (doc.get("repos") or {}).items():
        merged = dict(repos.get(repo_name) or {})
        merged.update(repo or {})
        repos[repo_name] = merged
    return repos


def head(url, branch):
    out = subprocess.run(
        ["git", "ls-remote", url, f"refs/heads/{branch}"],
        check=True, capture_output=True, text=True, timeout=120,
    ).stdout.split()
    if not out:
        raise SystemExit(f"{url}: branch {branch} not found")
    return out[0]


def lock_text(target, pins):
    lines = [
        f"# Generated by scripts/lock-layers.py for kas/{target}: the exact layer",
        "# commits for this target. Update with the script, never by hand.",
        "header:",
        "  version: 14",
        "overrides:",
        "  repos:",
    ]
    for name in sorted(pins):
        lines += [f"    {name}:", f"      commit: {pins[name]}"]
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv[1:]
    cache = {}
    stale = []
    for target in TARGETS:
        pins = {}
        for name, repo in sorted(load(target).items()):
            url, branch = repo.get("url"), repo.get("branch")
            if not url:
                continue  # this repository (castmill-os) itself
            if not branch:
                raise SystemExit(f"kas/{target}: {name} has no branch to pin")
            key = (url, str(branch))
            if key not in cache:
                cache[key] = head(url, branch)
            pins[name] = cache[key]
        path = os.path.join(KAS_DIR, target.replace(".yml", ".lock.yml"))
        text = lock_text(target, pins)
        current = open(path).read() if os.path.exists(path) else ""
        if current == text:
            print(f"kas/{os.path.basename(path)}: up to date")
            continue
        stale.append(os.path.basename(path))
        if check:
            print(f"kas/{os.path.basename(path)}: newer layer commits available")
        else:
            with open(path, "w") as f:
                f.write(text)
            print(f"kas/{os.path.basename(path)}: written ({len(pins)} layers)")
    if check and stale:
        sys.exit(1)


if __name__ == "__main__":
    main()
